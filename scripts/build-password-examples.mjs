// Builds the code shown on the password docs from the example components themselves,
// so every snippet is a file that the site type-checks, lints and renders.
// Usage: node scripts/build-password-examples.mjs (re-run after editing an example)
import { readFileSync, writeFileSync } from "node:fs";

const dir = "src/features/docs/content/password/examples";

/** File in this folder → path shown in the docs. */
const shownPath = {
  "password-policy.ts": "lib/password-policy.ts",
  "password-messages.ts": "lib/password-messages.ts",
  "password-input.tsx": "components/password-input.tsx",
  "signup-action.ts": "app/signup/actions.ts",
  "pwned-action.ts": "app/signup/pwned-action.ts",
};

const examples = {
  "show-hide": ["ShowHideExample.tsx", "password-input.tsx"],
  "strength-meter": ["StrengthMeterExample.tsx", "password-policy.ts", "password-messages.ts"],
  confirm: ["ConfirmPasswordExample.tsx"],
  "react-hook-form-zod": [
    "ReactHookFormZodExample.tsx",
    "password-policy.ts",
    "password-messages.ts",
  ],
  "server-action": ["ServerActionExample.tsx", "signup-action.ts", "password-policy.ts"],
  forbidden: ["ForbiddenExample.tsx", "password-policy.ts"],
  pwned: ["PwnedExample.tsx", "pwned-action.ts"],
  "mask-signup": ["MaskSignupExample.tsx", "password-policy.ts", "password-messages.ts"],
  "password-input": ["password-input.tsx"],
  "password-policy": ["password-policy.ts"],
};

const toImport = (file) => `@/${shownPath[file].replace(/\.tsx?$/, "")}`;

function show(file) {
  let code = readFileSync(`${dir}/${file}`, "utf8").trimEnd();
  for (const local of Object.keys(shownPath)) {
    code = code.replaceAll(`"./${local.replace(/\.tsx?$/, "")}"`, `"${toImport(local)}"`);
  }
  const header =
    shownPath[file] ??
    `components/${file
      .replace(/Example\.tsx$/, "")
      .replace(/([a-z])([A-Z])/g, "$1-$2")
      .toLowerCase()}.tsx`;
  return `// ${header}\n${code}`;
}

const entries = Object.entries(examples).map(
  ([id, files]) => `  ${JSON.stringify(id)}: ${JSON.stringify(files.map(show).join("\n\n"))},`,
);

writeFileSync(
  `${dir}/example-code.generated.ts`,
  `// Generated by scripts/build-password-examples.mjs. Do not edit.\n\nexport const passwordExampleCode = {\n${entries.join("\n")}\n} as const;\n\nexport type PasswordExampleCodeId = keyof typeof passwordExampleCode;\n`,
);
process.stdout.write(`Wrote ${entries.length} examples\n`);
