// Builds the code shown on the password docs from the example files themselves. The live previews
// render the same files, so the code on the page is exactly what runs.
// Usage: node scripts/build-password-examples.mjs (re-run after editing an example)
import { readFileSync, writeFileSync } from "node:fs";

const dir = "src/features/docs/content/password/examples";

/** Shared file in the examples folder → path shown in the docs. */
const shownPath = {
  "password-policy.ts": "lib/password-policy.ts",
  "password-messages.ts": "lib/password-messages.ts",
  "signup-action.ts": "app/signup/actions.ts",
  "pwned-action.ts": "app/signup/pwned-action.ts",
};

/** id → [file, shown path][]: the first file sits next to the preview, the rest below it. */
const examples = {
  "show-hide": [["sketches/show-hide.tsx", "components/password-field.tsx"]],
  "strength-meter": [["sketches/strength-meter.tsx", "components/new-password-field.tsx"]],
  confirm: [["sketches/confirm.tsx", "components/new-password-fields.tsx"]],
  "react-hook-form-zod": [["sketches/react-hook-form-zod.tsx", "components/signup-form.tsx"]],
  "server-action": [
    ["sketches/server-action.tsx", "components/signup-form.tsx"],
    ["signup-action.ts", "app/signup/actions.ts"],
  ],
  forbidden: [["sketches/forbidden.tsx", "components/new-password-field.tsx"]],
  pwned: [
    ["sketches/pwned.tsx", "components/leak-check.tsx"],
    ["pwned-action.ts", "app/signup/pwned-action.ts"],
  ],
  "mask-signup": [["sketches/mask-signup.tsx", "components/signup-form.tsx"]],
  basic: [["sketches/basic.tsx", "components/password-field.tsx"]],
  "custom-icons": [["sketches/custom-icons.tsx", "components/password-field.tsx"]],
  "custom-text": [["sketches/custom-text.tsx", "components/password-field.tsx"]],
  disabled: [["sketches/disabled.tsx", "components/locked-password-field.tsx"]],
  "prop-merge": [["sketches/prop-merge.tsx", "components/new-password-field.tsx"]],
  programmatic: [["sketches/programmatic.tsx", "components/password-field.tsx"]],
  shadcn: [["sketches/shadcn.tsx", "components/password-field.tsx"]],
};

const toImport = (file) => `@/${shownPath[file].replace(/\.tsx?$/, "")}`;

function show(file, path) {
  let code = readFileSync(`${dir}/${file}`, "utf8").trimEnd();
  for (const local of Object.keys(shownPath)) {
    const name = local.replace(/\.tsx?$/, "");
    code = code
      .replaceAll(`"../${name}"`, `"${toImport(local)}"`)
      .replaceAll(`"./${name}"`, `"${toImport(local)}"`);
  }
  return `// ${path}\n${code}`;
}

const sketchEntries = Object.entries(examples).map(
  ([id, files]) =>
    `  ${JSON.stringify(id)}: ${JSON.stringify(files.map(([file, path]) => show(file, path)))},`,
);
const fileEntries = Object.entries(shownPath).map(
  ([file, path]) =>
    `  ${JSON.stringify(file.replace(/\.tsx?$/, ""))}: ${JSON.stringify(show(file, path))},`,
);

writeFileSync(
  `${dir}/example-code.generated.ts`,
  `// Generated by scripts/build-password-examples.mjs. Do not edit.\n\n/** Example code: the first file sits next to the preview, the rest below it. */\nexport const passwordExampleSketch = {\n${sketchEntries.join("\n")}\n} as const;\n\nexport type PasswordExampleCodeId = keyof typeof passwordExampleSketch;\n\n/** Shared files, e.g. the policy shown on the strength page. */\nexport const passwordExampleFile = {\n${fileEntries.join("\n")}\n} as const;\n`,
);
process.stdout.write(`Wrote ${sketchEntries.length} examples\n`);
