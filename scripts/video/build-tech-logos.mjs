/**
 * Turns the site's logo components (src/components/ui/svgs) into plain inline
 * SVG strings for the video pages, so the frames use the same artwork as the site.
 *
 * Writes scripts/video/tech-logos.js (`window.TECH_LOGOS`):
 *   node scripts/video/build-tech-logos.mjs
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const svgs = path.resolve(here, "../../src/components/ui/svgs");

/** Logo key → component file (light-theme artwork). */
const LOGOS = {
  nextjs: "nextjsIconDark",
  react: "reactLight",
  typescript: "typescript",
  tanstack: "tanstackLight",
  zustand: "zustand",
  nuqs: "nuqs",
  reactHookForm: "reactHookForm",
  zod: "zod",
  baseUi: "baseUi",
  motion: "motion",
  lucide: "lucide",
  vitest: "vitest",
  claude: "claudeAiIcon",
  cursor: "cursorLight",
  testingLibrary: "testingLibrary",
};

const ATTRS = {
  fillRule: "fill-rule",
  clipRule: "clip-rule",
  clipPath: "clip-path",
  strokeWidth: "stroke-width",
  strokeLinecap: "stroke-linecap",
  strokeLinejoin: "stroke-linejoin",
  strokeMiterlimit: "stroke-miterlimit",
  strokeOpacity: "stroke-opacity",
  strokeDasharray: "stroke-dasharray",
  fillOpacity: "fill-opacity",
  stopColor: "stop-color",
  stopOpacity: "stop-opacity",
  floodOpacity: "flood-opacity",
  floodColor: "flood-color",
  colorInterpolationFilters: "color-interpolation-filters",
  xlinkHref: "href",
};

function toSvg(key, source) {
  const start = source.indexOf("<svg");
  const end = source.lastIndexOf("</svg>") + "</svg>".length;
  let svg = source.slice(start, end);

  svg = svg.replace(/\s*\{\.\.\.props\}/g, "");
  svg = svg.replace(/style=\{\{\s*maskType:\s*"alpha"\s*\}\}/g, 'style="mask-type:alpha"');
  svg = svg.replace(/\b(\w+)=/g, (m, name) => (ATTRS[name] ? `${ATTRS[name]}=` : m));
  // useId() output baked into the files (":r8:") would collide across logos.
  svg = svg.replace(/:r[0-9a-z]+:/g, `${key}-`);
  svg = svg.replace(/\saria-label="[^"]*"/g, "");

  if (/=\{/.test(svg)) throw new Error(`${key}: unconverted JSX expression`);
  return svg.replace(/\s+/g, " ");
}

const out = {};
for (const [key, file] of Object.entries(LOGOS)) {
  out[key] = toSvg(key, await fs.readFile(path.join(svgs, `${file}.tsx`), "utf8"));
}

await fs.writeFile(
  path.join(here, "tech-logos.js"),
  `/* Generated by build-tech-logos.mjs — do not edit. */\nwindow.TECH_LOGOS = ${JSON.stringify(out, null, 2)};\n`,
);
process.stdout.write(`${Object.keys(out).length} logos → scripts/video/tech-logos.js\n`);
